# ZigFS local HTTPS helper. Run on the Windows machine hosting ZigFS Admin.
# This script contains only the public CA. Inspect it before approving UAC.
param(
    [ValidateSet('install', 'uninstall')]
    [string]$Action = 'install'
)

$ErrorActionPreference = 'Stop'
if ($env:OS -ne 'Windows_NT') {
    throw 'This helper requires Windows.'
}
$identity = [Security.Principal.WindowsIdentity]::GetCurrent()
$principal = New-Object Security.Principal.WindowsPrincipal($identity)
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    $arguments = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', ('"{0}"' -f $PSCommandPath), '-Action', $Action)
    $process = Start-Process -FilePath "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -ArgumentList $arguments -Verb RunAs -Wait -PassThru
    if ($process.ExitCode -ne 0) {
        throw 'Elevated setup failed. Open PowerShell as administrator and rerun this command to see the detailed error.'
    }
    exit 0
}

$certificate = [Security.Cryptography.X509Certificates.X509Certificate2]::new([Convert]::FromBase64String('__CA_DER__'))
$sha256 = [Security.Cryptography.SHA256]::Create()
$fingerprint = [BitConverter]::ToString($sha256.ComputeHash($certificate.RawData)).Replace('-', '')
$sha256.Dispose()
Write-Host "ZigFS CA SHA-256: $fingerprint"
$hostsPath = Join-Path $env:SystemRoot 'System32\drivers\etc\hosts'
$begin = '# BEGIN ZigFS Local HTTPS'
$end = '# END ZigFS Local HTTPS'
$managed = "$begin`r`n# CA SHA-256: $fingerprint`r`n__TARGET_IP__ __ADMIN_DOMAIN__`r`n__TARGET_IP__ __S3_DOMAIN__`r`n$end"
$store = New-Object Security.Cryptography.X509Certificates.X509Store('Root', 'LocalMachine')
$mutex = New-Object Threading.Mutex($false, 'Global\ZigFSLocalHTTPSSetup')
$locked = $false

function Write-Hosts([string]$Content, [Text.Encoding]$Encoding) {
    # Write beside hosts and atomically replace it; Windows retains target ACLs.
    $temporary = "$hostsPath.zigfs-$([Guid]::NewGuid().ToString('N')).tmp"
    try {
        [IO.File]::WriteAllText($temporary, $Content, $Encoding)
        [IO.File]::Replace($temporary, $hostsPath, "$hostsPath.zigfs.backup", $true)
    } finally {
        if ([IO.File]::Exists($temporary)) {
            [IO.File]::Delete($temporary)
        }
    }
}

try {
    $locked = $mutex.WaitOne(0)
    if (-not $locked) {
        throw 'Another ZigFS setup is running. Retry after it finishes.'
    }
    if (([IO.File]::GetAttributes($hostsPath) -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw 'Refusing to modify a redirected hosts file.'
    }
    $reader = New-Object IO.StreamReader($hostsPath, (New-Object Text.UTF8Encoding($false, $true)), $true)
    try {
        $original = $reader.ReadToEnd()
        $encoding = $reader.CurrentEncoding
    } finally {
        $reader.Dispose()
    }
    $pattern = '(?m)^' + [regex]::Escape($begin) + '\r?\n[\s\S]*?^' + [regex]::Escape($end) + '(?=\r?$)'
    $blocks = [regex]::Matches($original, $pattern)
    $beginCount = [regex]::Matches($original, '(?m)^' + [regex]::Escape($begin) + '\r?$').Count
    $endCount = [regex]::Matches($original, '(?m)^' + [regex]::Escape($end) + '\r?$').Count
    if ($blocks.Count -gt 1 -or $beginCount -ne $blocks.Count -or $endCount -ne $blocks.Count) {
        throw 'The ZigFS hosts block is malformed or duplicated. Nothing changed.'
    }
    if ($blocks.Count -eq 1) {
        $oldBlock = $blocks[0].Value
        if ($oldBlock -notmatch ('(?m)^# CA SHA-256: ' + $fingerprint + '\r?$')) {
            throw 'Another ZigFS CA owns the hosts block. Uninstall it with its original helper first.'
        }
        # Accept only the exact format generated by this helper. Preserve user edits.
        $validBlock = '^' + [regex]::Escape($begin) + '\r?\n# CA SHA-256: ' + $fingerprint + '\r?\n(?<target>[0-9.]+) [a-z0-9.-]+\r?\n\k<target> [a-z0-9.-]+\r?\n' + [regex]::Escape($end) + '$'
        if ($oldBlock -notmatch $validBlock) {
            throw 'The managed hosts block was edited. Nothing changed.'
        }
    }
    $withoutBlock = [regex]::Replace($original, $pattern, '')
    if ($Action -eq 'install') {
        foreach ($line in ($withoutBlock -split '\r?\n')) {
            $record = ($line -split '#', 2)[0].Trim()
            $fields = $record -split '\s+'
            if ($fields.Count -lt 2) { continue }
            foreach ($name in $fields[1..($fields.Count - 1)]) {
                if ($name.TrimEnd('.') -in @('__ADMIN_DOMAIN__', '__S3_DOMAIN__')) {
                    throw "Existing hosts entry for $name conflicts with ZigFS. Nothing changed."
                }
            }
        }
        if ($blocks.Count -eq 1) {
            $updated = [regex]::Replace($original, $pattern, $managed)
        } else {
            $separator = if ($original.Length -eq 0 -or $original.EndsWith("`n")) { '' } else { "`r`n" }
            $updated = $original + $separator + $managed + "`r`n"
        }
    } else {
        $updated = $withoutBlock
    }

    $store.Open([Security.Cryptography.X509Certificates.OpenFlags]::ReadWrite)
    $existingCertificates = $store.Certificates.Find([Security.Cryptography.X509Certificates.X509FindType]::FindByThumbprint, $certificate.Thumbprint, $false)
    if ($Action -eq 'install') {
        $added = $existingCertificates.Count -eq 0
        if ($added) { $store.Add($certificate) }
        try {
            if ($updated -cne $original) { Write-Hosts $updated $encoding }
        } catch {
            if ($added) { $store.Remove($certificate) }
            throw
        }
    } else {
        if ($updated -cne $original) { Write-Hosts $updated $encoding }
        try {
            foreach ($match in $existingCertificates) { $store.Remove($match) }
        } catch {
            if ($updated -cne $original) { Write-Hosts $original $encoding }
            throw
        }
    }
    & "$env:SystemRoot\System32\ipconfig.exe" /flushdns
    if ($LASTEXITCODE -ne 0) {
        Write-Warning 'Configuration changed, but the DNS cache could not be flushed. Restart Windows before verification.'
    }
    Write-Host "ZigFS $Action completed. Restart the browser and verify HTTPS in ZigFS settings."
    Write-Host "Hosts backup: $hostsPath.zigfs.backup"
} finally {
    $store.Close()
    $certificate.Dispose()
    if ($locked) { $mutex.ReleaseMutex() }
    $mutex.Dispose()
}
