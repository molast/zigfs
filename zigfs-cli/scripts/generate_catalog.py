"""Generate the single-instance CLI catalog from pinned S3/OpenAPI inputs.
Run from repo root. No network, no runtime code generation.
"""
import json, re, hashlib
from pathlib import Path
base = Path('zigfs-cli')
source = json.loads((base / 'models/s3.json').read_text())
doc = Path('zigfs-cli/docs/zigfs-zc-cli-rustfs-reference.md').read_text()
rows = re.findall('^\\| `([A-Z][A-Za-z0-9]+)` \\| `(.*?)` \\| (单机规划|旧协议兼容) \\|$', doc, re.M)

def kebab(s):
    return re.sub('([a-z0-9])([A-Z])', '\\1-\\2', re.sub('([A-Z]+)([A-Z][a-z])', '\\1-\\2', s)).lower()

def strip(v):
    if isinstance(v, dict):
        return {k: strip(x) for k, x in v.items() if k not in ('documentation', 'documentationUrl')}
    if isinstance(v, list):
        return [strip(x) for x in v]
    return v
ops = {k: strip(source['operations'][k]) for k, _, _ in rows}
seen = set()

def visit(x):
    if isinstance(x, dict):
        if 'shape' in x:
            name = x['shape']
            if name not in seen:
                seen.add(name)
                visit(source['shapes'][name])
        for v in x.values():
            visit(v)
    elif isinstance(x, list):
        for v in x:
            visit(v)
for x in ops.values():
    visit(x)
model = {'metadata': source['metadata'], 'operations': {kebab(k): v for k, v in ops.items()}, 'shapes': {k: strip(source['shapes'][k]) for k in sorted(seen)}}
(base / 'src/models/s3.json').write_text(json.dumps(model, separators=(',', ':')) + '\n')
management = json.loads((base / 'models/management.json').read_text())
(base / 'src/models/management.json').write_text(json.dumps(strip(management), separators=(',', ':')) + '\n')
existing = Path('zigfs-cli/src/cli.zig').read_text()
registered = set(re.findall('\\.path = "([^"]+)"', existing))
commands = {}
for operation, path, _ in rows:
    op = kebab(operation)
    commands['s3api ' + op] = op
    high = path.split(' <')[0].split(' --')[0]
    if high.startswith('s3api '):
        continue
    if operation == 'ListObjects':
        high = 'object list-v1'
    if operation in ['PutObject', 'GetObject', 'CopyObject', 'DeleteObject', 'DeleteObjects', 'HeadObject', 'ListObjectsV2', 'CreateBucket', 'DeleteBucket', 'ListBuckets', 'HeadBucket', 'GetBucketLocation', 'GetBucketVersioning', 'CreateMultipartUpload', 'UploadPart', 'ListParts', 'ListMultipartUploads', 'CompleteMultipartUpload', 'AbortMultipartUpload']:
        continue
    commands[high] = op
for family in ['bucket encryption', 'object legalhold', 'object retention', 'bucket lock']:
    if family + ' info' in commands:
        commands[family + ' get'] = commands[family + ' info']
    if family + ' get' in commands:
        commands[family + ' info'] = commands[family + ' get']
commands['bucket version get'] = 'get-bucket-versioning'
new = {k: v for k, v in commands.items() if k not in registered}
lines = ['// Generated by scripts/generate_catalog.py; logic is in modeled.zig.', 'pub const entries = .{']
for path, op in sorted(new.items()):
    lines.append('    .{ .path = ' + json.dumps(path) + ', .operation = ' + json.dumps(op) + ' },')
lines.append('};')
(base / 'src/catalog.zig').write_text('\n'.join(lines) + '\n')
(base / 'src/models/provenance.json').write_text(json.dumps({'s3_source': 'https://github.com/boto/botocore/blob/develop/botocore/data/s3/2006-03-01/service-2.json', 's3_downloaded': '2026-11-17', 's3_sha256': hashlib.sha256((base / 'models/s3.json').read_bytes()).hexdigest(), 'management_source': 'docs/api/zigfs-management-v1.openapi.yaml', 'management_sha256': hashlib.sha256(Path('docs/api/zigfs-management-v1.openapi.yaml').read_bytes()).hexdigest(), 'operations': len(ops), 'status': 'pending validation'}, indent=2) + '\n')
print(len(ops), 'S3 operations;', len(new), 'new command mappings')
